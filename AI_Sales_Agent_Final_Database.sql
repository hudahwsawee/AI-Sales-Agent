SELECT DATE '2026-03-01' AS period_start, DATE '2026-03-31' AS period_end,
 ROUND(SUM(CASE WHEN status<>'cancelled' THEN gross_sales ELSE 0 END),2) AS gross_sales,
 ROUND(SUM(net_sales),2) AS net_sales
FROM sales_analytics
WHERE order_date>=DATE '2026-03-01' AND order_date<DATE '2026-04-01';

-- Verification: February vs March 2026
WITH monthly_sales AS (
 SELECT DATE_TRUNC('month',order_date)::date AS month,
 ROUND(SUM(CASE WHEN status<>'cancelled' THEN gross_sales ELSE 0 END),2) AS gross_sales,
 ROUND(SUM(net_sales),2) AS net_sales
 FROM sales_analytics
 WHERE order_date>=DATE '2026-02-01' AND order_date<DATE '2026-04-01'
 GROUP BY DATE_TRUNC('month',order_date)
)
SELECT month,gross_sales,net_sales,
 ROUND(((net_sales-LAG(net_sales) OVER(ORDER BY month))/
 NULLIF(LAG(net_sales) OVER(ORDER BY month),0))*100,2) AS growth_percentage
FROM monthly_sales ORDER BY month;
