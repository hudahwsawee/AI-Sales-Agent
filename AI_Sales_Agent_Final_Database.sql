-- AI SALES AGENT - Final Database Setup
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE customers (
 customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_name TEXT NOT NULL, city TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE products (
 product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_name TEXT NOT NULL, category TEXT NOT NULL,
 current_price NUMERIC(12,2) NOT NULL CHECK (current_price >= 0),
 created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE orders (
 order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
 order_date DATE NOT NULL,
 status TEXT NOT NULL CHECK (status IN ('completed','cancelled','returned','processing')),
 sales_channel TEXT NOT NULL CHECK (sales_channel IN ('store','online')),
 branch TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT NOW()
);
CREATE TABLE order_items (
 order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
 product_id BIGINT NOT NULL REFERENCES products(product_id),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
 discount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
 return_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (return_amount >= 0)
);
CREATE INDEX idx_orders_date ON orders(order_date);
CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_order_items_order ON order_items(order_id);
CREATE INDEX idx_order_items_product ON order_items(product_id);

