CREATE OR REPLACE VIEW public.sales_analytics AS
SELECT o.order_id,o.order_date,o.customer_id,c.customer_name,c.city,o.status,
 o.sales_channel,o.branch,oi.order_item_id,oi.product_id,p.product_name,p.category,
 oi.quantity,oi.unit_price,round(oi.quantity::numeric*oi.unit_price,2) AS gross_sales,
 oi.discount,oi.return_amount,
 CASE WHEN o.status='cancelled'::text THEN 0::numeric
 ELSE round(oi.quantity::numeric*oi.unit_price-oi.discount-oi.return_amount,2) END AS net_sales
FROM orders o JOIN customers c ON o.customer_id=c.customer_id
JOIN order_items oi ON o.order_id=oi.order_id JOIN products p ON oi.product_id=p.product_id;

CREATE TABLE documents (
 id BIGSERIAL PRIMARY KEY, content TEXT, metadata JSONB, embedding VECTOR(1536)
);
CREATE TABLE public.sales_knowledge (
 id BIGSERIAL PRIMARY KEY, content TEXT, metadata JSONB, embedding VECTOR(1536)
);

CREATE OR REPLACE FUNCTION match_documents(
 query_embedding VECTOR(1536), match_count INT DEFAULT NULL, filter JSONB DEFAULT '{}')
RETURNS TABLE(id BIGINT,content TEXT,metadata JSONB,similarity FLOAT)
LANGUAGE plpgsql AS $$
#variable_conflict use_column
BEGIN
 RETURN QUERY SELECT id,content,metadata,
 1-(documents.embedding <=> query_embedding) AS similarity
 FROM documents WHERE metadata @> filter
 ORDER BY documents.embedding <=> query_embedding LIMIT match_count;
END; $$;

CREATE OR REPLACE FUNCTION match_sales_knowledge(
 query_embedding VECTOR(1536), match_threshold FLOAT, match_count INT)
RETURNS TABLE(id BIGINT,content TEXT,metadata JSONB,similarity FLOAT)
LANGUAGE sql STABLE AS $$
 SELECT sales_knowledge.id,sales_knowledge.content,sales_knowledge.metadata,
 1-(sales_knowledge.embedding <=> query_embedding) AS similarity
 FROM sales_knowledge
 WHERE 1-(sales_knowledge.embedding <=> query_embedding)>match_threshold
 ORDER BY sales_knowledge.embedding <=> query_embedding LIMIT match_count;
$$;

